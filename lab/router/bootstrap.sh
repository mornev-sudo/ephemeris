#!/usr/bin/env bash
# Prepare a Debian 13 VM to run ephemerisd, build it, and install it as a
# service. Run from the repo root on the router VM:  sudo lab/router/bootstrap.sh
#
# Phase 3 replaces all of this with an immutable image; for now it's a plain VM.
set -euo pipefail

DATA_DEVS=${DATA_DEVS:-"ens19 ens20"}   # NICs handed to the data plane (NOT the mgmt NIC)
WORKERS=${WORKERS:-2}                   # must match ROUTER_QUEUES in create-lab.sh
HUGEPAGES=${HUGEPAGES:-256}             # 2 MiB pages: 512 MiB for packet buffers
REPO=$(cd "$(dirname "$0")/../.." && pwd)
USER_HOME=$(getent passwd "${SUDO_USER:-root}" | cut -d: -f6)

[[ $EUID -eq 0 ]] || { echo "run with sudo"; exit 1; }

echo "== packages"
apt-get update -qq
apt-get install -y -qq build-essential pkg-config curl git ethtool tcpdump iperf3 \
    qemu-guest-agent linux-perf bpftool >/dev/null
systemctl enable --now qemu-guest-agent >/dev/null 2>&1 || true

echo "== rust (for user ${SUDO_USER:-root})"
if [[ ! -x $USER_HOME/.cargo/bin/cargo ]]; then
    sudo -u "${SUDO_USER:-root}" bash -c \
        'curl --proto =https --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal'
fi

echo "== huge pages ($HUGEPAGES x 2 MiB)"
echo "vm.nr_hugepages = $HUGEPAGES" > /etc/sysctl.d/60-ephemeris.conf
sysctl -q -p /etc/sysctl.d/60-ephemeris.conf

echo "== data-plane NICs: $DATA_DEVS"
# A small systemd unit applies NIC settings at every boot, before ephemerisd.
cat > /usr/local/sbin/ephemeris-nic-setup <<SH
#!/bin/sh
# Generated by lab/router/bootstrap.sh
for dev in $DATA_DEVS; do
    ip addr flush dev "\$dev"                 # the kernel must not own these links
    sysctl -qw "net.ipv6.conf.\$dev.disable_ipv6=1"   # ...or chatter IPv6 out of them
    ip link set dev "\$dev" up
    ethtool -L "\$dev" combined $WORKERS 2>/dev/null || true   # one RX queue per worker
    ethtool -K "\$dev" gro off lro off 2>/dev/null || true     # native XDP needs plain frames
    # Symmetric RSS: both directions of a flow hash to the same queue, so the
    # same worker (and its session table) sees them. Real NICs on kernel 6.10+
    # support this; virtio ignores it (see docs/learn/07-sessions.md).
    ethtool -X "\$dev" hfunc toeplitz symmetric-xor 2>/dev/null || true
done
SH
chmod +x /usr/local/sbin/ephemeris-nic-setup
cat > /etc/systemd/system/ephemeris-nic-setup.service <<UNIT
[Unit]
Description=Prepare Ephemeris data-plane NICs
After=network-pre.target
Before=ephemerisd.service
[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/ephemeris-nic-setup
[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable --now ephemeris-nic-setup.service

echo "== build"
sudo -u "${SUDO_USER:-root}" bash -c "cd '$REPO' && \$HOME/.cargo/bin/cargo build --release"
install -m 0755 "$REPO/target/release/ephemerisd" /usr/local/sbin/ephemerisd
install -m 0755 "$REPO/target/release/ephctl" /usr/local/bin/ephctl

echo "== config + service"
mkdir -p /etc/ephemeris
if [[ ! -f /etc/ephemeris/ephemeris.toml ]]; then
    set -- $DATA_DEVS
    sed -e "s/^workers = .*/workers = $WORKERS/" \
        -e "s/device = \"ens19\"/device = \"$1\"/" \
        -e "s/device = \"ens20\"/device = \"$2\"/" \
        "$REPO/config/ephemeris.example.toml" > /etc/ephemeris/ephemeris.toml
fi
install -m 0644 "$REPO/lab/router/ephemerisd.service" /etc/systemd/system/ephemerisd.service
systemctl daemon-reload
ephemerisd --check --config /etc/ephemeris/ephemeris.toml

cat <<MSG

Ready. Start the router with:
    sudo systemctl enable --now ephemerisd
    journalctl -u ephemerisd -f

Or run it in the foreground while experimenting:
    sudo RUST_LOG=debug ephemerisd --config /etc/ephemeris/ephemeris.toml

Quick check without the clients:  sudo lab/netns/selftest.sh /usr/local/sbin/ephemerisd
MSG
